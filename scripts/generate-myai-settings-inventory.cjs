#!/usr/bin/env node
/**
 * Generates docs/MYAI_SETTINGS_INVENTORY.md from package.json contributes.configuration.properties.
 * Run from extension root: npm run docs:settings-inventory
 */
"use strict";

const { readFileSync, writeFileSync, mkdirSync } = require("node:fs");
const { dirname, join } = require("node:path");

const root = join(__dirname, "..");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const props = pkg.contributes?.configuration?.properties;
if (!props || typeof props !== "object") {
  console.error("No contributes.configuration.properties in package.json");
  process.exit(1);
}

const keys = Object.keys(props).filter((k) => k.startsWith("myAi.")).sort();

function fmtDefault(v) {
  if (v === undefined) return "—";
  if (typeof v === "string") return `\`${v.replace(/`/g, "'")}\``;
  return `\`${JSON.stringify(v)}\``;
}

const rows = keys.map((key) => {
  const p = props[key];
  const desc = (p.description || "").replace(/\|/g, "\\|").replace(/\n/g, " ");
  const typ = Array.isArray(p.type) ? p.type.join(" \\| ") : p.type ?? "—";
  return `| \`${key}\` | ${typ} | ${fmtDefault(p.default)} | ${desc} |`;
});

const out = `<!-- AUTO-GENERATED by npm run docs:settings-inventory — do not edit by hand -->
# \`myAi.*\` settings inventory

Generated from \`package.json\` \`contributes.configuration.properties\`. Regenerate after changing contributed settings:

\`\`\`bash
cd autonomous_factory
npm run docs:settings-inventory
\`\`\`

## Table

| Key | Type | Default | Description |
| --- | --- | --- | --- |
${rows.join("\n")}

## Finding code references

Contributed keys use dotted form. To find where a setting is **read** in this extension:

\`\`\`bash
rg 'myAi\\\\.missions\\\\.portableJson' src
# or broader:
rg 'getConfiguration\\\\(' src | head -80
\`\`\`

This table does **not** list every callsite — only defaults and descriptions from \`package.json\`.
`;

const dest = join(root, "docs", "MYAI_SETTINGS_INVENTORY.md");
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, out, "utf8");
console.info("Wrote", dest, "(" + keys.length + " keys)");
